#!/usr/bin/env python3
"""
Turn baked takes (bake.py's stroke JSON) into a Lua data file the addon
draws with its own pen (UI/Ink/Hand.lua), so no PNG ships.

    python tools/to_lua.py notes --out ../../UI/Ink/HandData.lua
    python tools/to_lua.py snagged=a.json,b.json died=c.json --out HandData.lua

Each argument is a note: `key=take.json[,take.json ...]`, one take per line
of the note, top to bottom; or a folder holding a folder per note (its name
the key), whose takes are its lines in file-name order (1.json, 2.json).

What it writes, per line of a note:
  - its strokes in x-heights (1 unit = the note's x-height, estimated from
    the tops of its letters), the origin at the left end of the line's
    baseline, y down: Lua scales a note to any size by one number;
  - each stroke simplified (Ramer-Douglas-Peucker, `--tolerance` x-heights),
    as flat triples x, y, p: p the ink width at that point over the take's
    median width (the pen's pressure, 1 = usual);
  - its width and how far it rises and falls (ascenders, descenders);
  - the text, style, seed and bias, so a take can be baked again.

Standard library only.
"""
import argparse
import json
import math
import statistics
from pathlib import Path


def rdp(points, tol):
    """Indices of the points kept by Ramer-Douglas-Peucker (ends always)."""
    n = len(points)
    if n < 3:
        return list(range(n))
    keep = [False] * n
    keep[0] = keep[-1] = True
    stack = [(0, n - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = points[a]
        bx, by = points[b]
        dx, dy = bx - ax, by - ay
        length = math.hypot(dx, dy)
        worst, at = -1.0, None
        for i in range(a + 1, b):
            px, py = points[i]
            if length < 1e-9:
                d = math.hypot(px - ax, py - ay)
            else:
                d = abs(dy * (px - ax) - dx * (py - ay)) / length
            if d > worst:
                worst, at = d, i
        if at is not None and worst > tol:
            keep[at] = True
            stack.append((a, at))
            stack.append((at, b))
    return [i for i in range(n) if keep[i]]


def tops(take):
    """Heights above the baseline (px) of every top of a stroke: where the
    pen turns from going up to going down (y down)."""
    base = take['baseline_y']
    out = []
    for s in take['strokes']:
        ys = [p[1] for p in s['points']]
        for i in range(1, len(ys) - 1):
            if ys[i] < ys[i - 1] and ys[i] <= ys[i + 1]:
                out.append(base - ys[i])
    return [h for h in out if h > 0]


def x_height(takes):
    """The note's x-height in px: most tops are a small letter's (the
    ascenders and the dots are the few), so the median of the tops, taken
    again over those under 1.4 times it to drop the tall ones' pull."""
    hs = [h for t in takes for h in tops(t)]
    if not hs:
        raise SystemExit('no letter tops found to measure an x-height')
    m = statistics.median(hs)
    low = [h for h in hs if h < 1.4 * m] or hs
    return statistics.median(low)


def convert_line(take, xh, tol):
    base = take['baseline_y']
    pts = [p for s in take['strokes'] for p in s['points']]
    left = min(p[0] for p in pts)
    widths = [w for s in take['strokes'] for w in s['width']]
    usual = statistics.median(widths) or 1.0
    strokes, kept = [], 0
    for s in take['strokes']:
        xy = [((p[0] - left) / xh, (p[1] - base) / xh) for p in s['points']]
        idx = rdp(xy, tol)
        if len(idx) == 1:
            idx = [0, 0]
        strokes.append([(xy[i][0], xy[i][1], s['width'][i] / usual) for i in idx])
        kept += len(idx)
    # From the left end of what was kept, rounded.
    shift = min(p[0] for st in strokes for p in st)
    strokes = [[v for x, y, w in st for v in (round(x - shift, 3), round(y, 3), round(w, 2))] for st in strokes]
    ys = [y for st in strokes for y in st[1::3]]
    xs = [x for st in strokes for x in st[0::3]]
    return {
        'text': take['text'], 'style': take['style'], 'seed': take['seed'], 'bias': take['bias'],
        'w': round(max(xs), 3), 'up': round(-min(ys), 3), 'down': round(max(ys), 3),
        'strokes': strokes, 'points': kept, 'raw': len(pts),
    }


def lua_number(v):
    s = ('%.3f' % v).rstrip('0').rstrip('.')
    return '0' if s in ('-0', '') else s


def lua_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def write_lua(notes, out, sources, tol):
    L = []
    L.append('-- Generated by Fonts/handwriting/tools/to_lua.py; do not edit by hand.')
    L.append('-- Bake new takes with Fonts/handwriting/bake.py and run the converter again')
    L.append('-- (Fonts/handwriting/README.md, "Into the addon"). Simplified to %s x-heights.' % lua_number(tol))
    L.append('--')
    L.append('-- From:')
    for src in sources:
        L.append('--   ' + src)
    L.append('--')
    L.append('-- The diary\'s baked handwriting (UI/Ink/Hand.lua draws it), by note: each')
    L.append('-- note { text, style, bias, lines }, each line { text, seed, w, up, down,')
    L.append('-- strokes }: x-heights from the left end of its baseline, y down; a stroke')
    L.append('-- flat x, y, p triples, p the pen\'s pressure (1 = its usual width).')
    L.append('')
    L.append('local addonName, ns = ...')
    L.append('')
    L.append('ns.UI.Hand.NOTES = {')
    for key in sorted(notes):
        lines = notes[key]
        first = lines[0]
        text = ' / '.join(l['text'] for l in lines)
        L.append('    %s = { text = %s, style = %s, bias = %s, lines = {' % (
            key, lua_string(text), first['style'], lua_number(first['bias'])))
        for l in lines:
            L.append('        { text = %s, seed = %s, w = %s, up = %s, down = %s, strokes = {' % (
                lua_string(l['text']), l['seed'], lua_number(l['w']), lua_number(l['up']), lua_number(l['down'])))
            for st in l['strokes']:
                L.append('            { ' + ', '.join(lua_number(v) for v in st) + ' },')
            L.append('        } },')
        L.append('    } },')
    L.append('}')
    out.write_text('\n'.join(L) + '\n')


def gather(args):
    """The notes asked for: { key: [json path, ...] }."""
    notes = {}
    for a in args:
        if '=' in a:
            key, files = a.split('=', 1)
            notes[key] = [Path(f) for f in files.split(',') if f]
        else:
            folder = Path(a)
            if not folder.is_dir():
                raise SystemExit('%s: not key=take.json,... nor a folder of notes' % a)
            for sub in sorted(p for p in folder.iterdir() if p.is_dir()):
                files = sorted(sub.glob('*.json'))
                if files:
                    notes[sub.name] = files
    for key in notes:
        if not key.isidentifier():
            raise SystemExit('note key %r must be a Lua name' % key)
    return notes


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('notes', nargs='+', help='key=take.json[,take.json ...] or a folder of note folders')
    p.add_argument('--out', type=Path, required=True, help='the Lua file to write')
    p.add_argument('--tolerance', type=float, default=0.035,
                   help='simplification, in x-heights (default 0.035: a third of a px at a 10 px x-height)')
    a = p.parse_args()

    notes, sources = {}, []
    for key, files in gather(a.notes).items():
        takes = [json.loads(f.read_text()) for f in files]
        xh = x_height(takes)
        notes[key] = [convert_line(t, xh, a.tolerance) for t in takes]
        for i, (f, t) in enumerate(zip(files, takes), 1):
            sources.append('%s, line %d: %s (%r, style %s, seed %s, bias %s)' % (
                key, i, f.as_posix(), t['text'], t['style'], t['seed'], t['bias']))
        kept = sum(l['points'] for l in notes[key])
        raw = sum(l['raw'] for l in notes[key])
        print('%s: x-height %.1f px, %d of %d points kept, %d strokes' % (
            key, xh, kept, raw, sum(len(l['strokes']) for l in notes[key])))
    write_lua(notes, a.out, sources, a.tolerance)
    print('wrote', a.out)


if __name__ == '__main__':
    main()

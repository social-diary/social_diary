#!/usr/bin/env python3
"""Writes a dungeon's pace data (Core/Pace/<Name>.lua) from the route-model
pipeline's output (ref/route-model-handover/pipeline/dungeons/<name>/:
page_data.json and config.json), for Core/DungeonPace.lua.

    python3 -I Dev/pace_export.py ref/route-model-handover/pipeline/dungeons/ragefire_chasm Core/Pace/RagefireChasm.lua

What it keeps: the entrance and the bosses in game yards (the anchors the
addon fits to its own map with), and every trash pack (a pull: where it
stands, its size, its elites, who is in it, and the boss whose room it
guards). Not the pipeline's legs, paths or transform: those were made for
its own reference map and its own shortest ways; the addon lays the packs
on the way it draws (Dungeon Crawler Forever's usual way, or the player's).

Standard library only. Never edit the Lua it writes: change the pipeline's
config.json, rerun the pipeline, then this.
"""
import json
import os
import sys


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def num(v):
    return ("%.2f" % v).rstrip("0").rstrip(".") if isinstance(v, float) else str(v)


def main(work, out):
    page = json.load(open(os.path.join(work, "page_data.json")))
    cfg = json.load(open(os.path.join(work, "config.json")))
    source = ("Spawns: advocaite/TrinityCore, branch forever, release forever-tdb-2026-10-14 "
              "(the vanilla world converted from VMaNGOS), GPL-2.0-or-later")
    L = []
    L.append("-- %s's pace data (instance %d), for Core/DungeonPace.lua. Generated by" % (page["dungeon"], page["mapId"]))
    L.append("-- Dev/pace_export.py from the route-model pipeline; do not edit by hand.")
    L.append("-- " + source + ".")
    L.append("-- Game yards (x north, y west): the entrance and the bosses, which the")
    L.append("-- addon fits its own map to, and every trash pack (where it stands, its")
    L.append("-- size and elites, who is in it, `boss` the boss whose room it guards).")
    L.append("-- Excluded by the pipeline's config: %s." % (", ".join(cfg.get("exclude", []) + cfg.get("no_pull", [])) or "nothing"))
    L.append("")
    L.append("local addonName, ns = ...")
    L.append("")
    L.append("local data = {")
    L.append("    name = %s, instanceID = %d," % (lua_str(page["dungeon"]), page["mapId"]))
    L.append("    source = %s," % lua_str(source))
    L.append("    entrance = { x = %s, y = %s }," % (num(float(page["entrance"]["x"])), num(float(page["entrance"]["y"]))))
    L.append("    bosses = {")
    for b in page["bosses"]:
        L.append("        { name = %s, x = %s, y = %s }," % (lua_str(b["name"]), num(float(b["x"])), num(float(b["y"]))))
    L.append("    },")
    L.append("    packs = {")
    for p in page["packs"]:
        names = ", ".join(lua_str(n) for n in p["names"])
        boss = (", boss = " + lua_str(p["boss"])) if p.get("boss") else ""
        L.append("        { x = %s, y = %s, size = %d, elites = %d, names = { %s }%s }," % (
            num(float(p["x"])), num(float(p["y"])), p["size"], p["elites"], names, boss))
    L.append("    },")
    L.append("}")
    L.append("")
    L.append("ns.PaceData = ns.PaceData or {}")
    L.append("ns.PaceData[data.instanceID] = data")
    L.append("return data")
    open(out, "w").write("\n".join(L) + "\n")
    print("%s: %d bosses, %d packs -> %s" % (page["dungeon"], len(page["bosses"]), len(page["packs"]), out))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])

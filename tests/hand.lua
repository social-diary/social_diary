-- The diary's baked handwriting: UI/Ink/HandData.lua as the converter
-- (Fonts/handwriting/tools/to_lua.py) writes it, and UI/Ink/Hand.lua
-- drawing a note with the pen: inside the box it measures, at any size
-- with the same pen, turned about its first baseline's left end.

local T = ...
local Section, Check, Eq = T.Section, T.Check, T.Eq
local ns = T.Boot()
local Hand = ns.UI.Hand
local HAND = Hand.HAND

--------------------------------------------------------------------------
Section("the generated data: valid Lua, a note's lines and strokes")

local here = (debug.getinfo(1, "S").source:match("^@(.*)[/\\]") or "tests")
local path = here .. "/../UI/Ink/HandData.lua"
local file = assert(io.open(path))
local head = file:read("*l")
file:close()
Check(head:find("Generated by Fonts/handwriting/tools/to_lua.py", 1, true), "HandData.lua does not say it is generated")
-- On its own, it only sets the notes on the hand's table.
local chunk = assert(loadfile(path))
local alone = { UI = { Hand = {} } }
chunk("social_diary", alone)
Check(type(alone.UI.Hand.NOTES) == "table", "HandData.lua sets no notes")
local keys = 0
for key, note in pairs(alone.UI.Hand.NOTES) do
    keys = keys + 1
    Check(type(note.text) == "string" and note.style and note.bias, key .. ": no text, style or bias to bake it again")
    Check(#note.lines >= 1, key .. ": no lines")
    for i, line in ipairs(note.lines) do
        local label = ("%s line %d"):format(key, i)
        Check(line.seed and line.text ~= "", label .. ": no seed or text")
        local minX, maxX = math.huge, -math.huge
        for _, st in ipairs(line.strokes) do
            Check(#st >= 6 and #st % 3 == 0, label .. ": a stroke not in x, y, p triples")
            for k = 1, #st, 3 do
                local x, y, p = st[k], st[k + 1], st[k + 2]
                Check(x == x and y == y and p > 0 and p < 5, label .. ": a bad point")
                minX, maxX = math.min(minX, x), math.max(maxX, x)
                Check(y >= -line.up - 1e-6 and y <= line.down + 1e-6, label .. ": a point past its rise or fall")
            end
        end
        Eq(minX, 0, label .. ": not from the left end of its baseline")
        Check(math.abs(maxX - line.w) < 1e-6, label .. ": its width not its strokes'")
    end
end
Check(keys >= 1, "no notes baked")
local snag = Hand.Note("snagged")
Check(snag and #snag.lines == 2, "the snagged note is not two lines")
Eq(snag.lines[1].text .. " / " .. snag.lines[2].text, "snagged an item / from me", "the snagged note's words")
Eq(Hand.Note("nothing baked"), nil, "a note never baked")
Eq(Hand.Note(nil), nil, "no key, no note")

--------------------------------------------------------------------------
Section("drawn with the pen: inside its box, the same pen at any size, turned")

local function Draw(size, turn, indent)
    local out = {}
    local made, box = Hand.Draw(out, snag, { x = 20, y = 30, size = size, turn = turn, indent = indent,
        colour = { 0.1, 0.1, 0.1 } })
    return out, made, box
end
for _, size in ipairs({ 6, 9, 14 }) do
    local out, made, box = Draw(size, 0)
    Eq(made, #out, "the pieces made not those returned")
    Check(made > 40 and made < 400, ("a note of %d pieces at %g px: too few or too many textures"):format(made, size))
    local w, h, top = Hand.Measure(snag, size)
    local pen = HAND.max
    Check(box[1] >= 20 - pen and box[3] <= 20 + w + pen, ("at %g px, wider than measured: %.1f..%.1f of %.1f"):format(
        size, box[1], box[3], w))
    Check(box[2] >= 30 - top - pen and box[4] <= 30 - top + h + pen, ("at %g px, taller than measured"):format(size))
    for _, q in ipairs(out) do
        Eq(q.k, "q", "not a quad")
        Check(q.x1 == q.x1 and q.y3 == q.y3 and q.a > 0, "a quad without a place or ink")
    end
end
-- The pen is the pen: its mean width hardly changes with the size.
local function MeanWidth(out)
    local sum = 0
    for _, q in ipairs(out) do sum = sum + math.sqrt((q.x1 - q.x4) ^ 2 + (q.y1 - q.y4) ^ 2) end
    return sum / #out
end
local small, big = MeanWidth((Draw(6, 0))), MeanWidth((Draw(14, 0)))
Check(small >= HAND.min * 0.9 and big <= HAND.max, ("the pen out of its widths: %.2f, %.2f"):format(small, big))
Check(math.abs(small - big) < 0.35, ("the pen grew with the note: %.2f at 6 px, %.2f at 14"):format(small, big))
-- Turned up: the first line's right end rises, its left end stays.
local flat, _, fb = Draw(10, 0)
local turned, _, tb = Draw(10, math.rad(5))
Check(tb[2] < fb[2] - 3, "turned up, its top did not rise")
Check(math.abs(tb[1] - fb[1]) < 4, "turned about its left end, it moved left or right")
-- A line moved right by its indent.
local _, _, ib = Draw(10, 0, { 0, 12 })
Check(ib[3] >= fb[3] - 1e-6, "an indent did not move its line")
Check(#flat == #turned, "turning changed the strokes")

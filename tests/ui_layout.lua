Section("ns.UI: loose names are entry points, the rest are modules")

-- Every page built, so what a page sets when it is built is there too.
ns.UI.ShowJournal()
for _, key in ipairs({ "journey", "people", "nearby", "settings" }) do ns.UI.SetJournalView(key) end
ns.UI.CloseJournal()

local stray, newModules, seen = {}, {}, {}
for name, value in pairs(ns.UI) do
    seen[name] = true
    if IsModule(value) then
        if not MODULES[name] then newModules[name] = true end
    elseif not LOOSE[name] then
        stray[name] = true
    end
end
Check(next(stray) == nil, "loose ns.UI names no other layer calls: " .. Sorted(stray)
    .. " (put each on its module's table, or add it to LOOSE in tests/ui_layout.lua with the caller that needs it)")
Check(next(newModules) == nil, "new ns.UI modules: " .. Sorted(newModules)
    .. " (add each to MODULES in tests/ui_layout.lua)")

local gone = {}
for name in pairs(LOOSE) do
    if not seen[name] then gone[name] = true end
end
for name in pairs(MODULES) do
    if not seen[name] then gone[name] = true end
end
Check(next(gone) == nil, "listed but not on ns.UI any more (take them off the lists): " .. Sorted(gone))

for name in pairs(LOOSE) do
    Check(not IsModule(ns.UI[name]), "ns.UI." .. name .. " is a module now: move it to MODULES")
end


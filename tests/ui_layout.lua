Section("ns.Style knows nothing of the diary")

-- What Style may not read: the diary's data and its modules, the settings
-- (a look that depends on one, the flat paper or the grain, takes it as an
-- argument or a /sd art value), and the UI above it. ns.Fire and ns.Print,
-- the addon's plumbing, are fine.
local FORBIDDEN = { "ns.db", "ns.Diary", "ns.Journey", "ns.JourneyRecap", "ns.Sessions", "ns.Interactions",
    "ns.Characters", "ns.Sightings", "ns.Notes", "ns.People", "ns.Reunions", "ns.Heat", "ns.Timeline",
    "ns.Setting(", "ns.SetSetting(", "ns.UI" }

local function Ls(cmd)
    local list, p = {}, assert(io.popen(cmd))
    for line in p:lines() do list[#list + 1] = line end
    p:close()
    return list
end

local files = Ls("find UI/Style -name '*.lua' 2>/dev/null | sort")
Check(#files >= 8, "UI/Style/ not found from " .. (os.getenv("PWD") or "?"))
for _, file in ipairs(files) do
    local f = assert(io.open(file, "r"))
    local reads, n = {}, 0
    for line in f:lines() do
        n = n + 1
        local code = line:gsub("%-%-.*$", "")
        for _, name in ipairs(FORBIDDEN) do
            -- A whole name: ns.Journey is not ns.JourneyRecap's prefix, nor
            -- ns.UI ns.UIParent's.
            local from = 1
            while true do
                local at = code:find(name, from, true)
                if not at then break end
                local after = code:sub(at + #name, at + #name)
                if name:sub(-1) == "(" or not after:match("[%w_]") then
                    reads[#reads + 1] = ("%d: %s"):format(n, name)
                end
                from = at + 1
            end
        end
    end
    f:close()
    Check(#reads == 0, ("%s reads the diary (Style knows nothing of it): %s"):format(file, table.concat(reads, ", ")))
end

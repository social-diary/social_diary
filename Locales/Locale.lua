-- Translations. Every word a player reads is looked up here, keyed by its
-- English text:
--
--   local L = ns.L
--   label:SetText(L["Keep my own route"])
--   ns.Fmt(L["Quested together for %s"], Duration(t))
--
-- A key is always a plain string literal (Dev/Locale/extract.lua finds the
-- keys by reading the source, so `L[name]` or `L["a" .. b]` are never
-- seen). A key not translated falls back to itself, so an English client,
-- and every client the diary has no words for yet, reads the English.
--
-- The files, loaded straight after Core/Addon.lua so a file can take its
-- words as it loads (`local PARTS = { L["Morning"], ... }`):
--   Locales/Locale.lua   this file: ns.L, ns.Fmt, ns.Locale
--   Locales/enUS.lua     every key, as the code writes it (generated by
--                        Dev/Locale/extract.lua; the translators' master list)
--   Locales/<id>/*.lua   a locale's words (deDE, frFR, ruRU, ...), a file
--                        per area of the addon, each listed in the TOC
--
-- A translation may reorder the values of a template with positional
-- placeholders, "%2$s ... %1$s" (ns.Fmt reads them: plain string.format
-- does not in every Lua). In one template they are all positional or none.
--
-- Grammar the templates can't carry (plurals, articles, ordinals, lists,
-- the "you" of a shared diary) is a function a locale may replace:
-- ns.Locale.grammar.<Name>. The English function stays in its own file and
-- asks first (`local G = ns.Locale.grammar` ... `if G.Plural then ...`).

local addonName, ns = ...

local Locale = {
    id = (GetLocale and GetLocale()) or "enUS",
    grammar = {},
}
ns.Locale = Locale

-- A key may carry a context after "##" where one English word needs two
-- translations ("May##short", the month's short form): the English is the
-- key without it.
local function English(key)
    return (key:gsub("##.*$", ""))
end
Locale.English = English

-- A key with no words is its own English, kept once asked: on an English
-- client every lookup comes here, the ones in a page's drawing too.
local L = setmetatable({}, {
    __index = function(t, key)
        local text = English(key)
        rawset(t, key, text)
        return text
    end,
})
ns.L = L

-- Adds a locale's words, if it is the client's. `id` "enUS" is always
-- taken: the English the code writes, as a base every locale builds on.
function Locale.Add(id, words)
    if id ~= "enUS" and id ~= Locale.id then return false end
    for key, text in pairs(words) do
        if type(text) == "string" then rawset(L, key, text) end
    end
    return true
end

-- Whether this client reads `id`'s words ("deDE"), for a locale file's
-- grammar: `if not ns.Locale.Is("deDE") then return end`.
function Locale.Is(id)
    return Locale.id == id
end

-- string.format with positional placeholders: "%2$s, %1$s" takes the
-- second value first. A template without them is plain string.format.
--
-- A locale may give grammar.Agree(text), a last pass over every filled
-- template, for words that arrive as values and must agree with a noun
-- the template holds: a number word's gender ("deux" before a masculine
-- noun, "une" for 1 before a feminine one). The locale picks its own mark
-- for its words to carry ("%s<f> morts") and resolves it there; English
-- has none.
local ESCAPED = "\1"
local function Fill(template, ...)
    if not template:find("%%%d+%$") then return template:format(...) end
    local values = { ... }
    local text = template:gsub("%%%%", ESCAPED)
    text = text:gsub("%%(%d+)%$([-+ #0]*%d*%.?%d*[%a])", function(i, spec)
        return ("%" .. spec):format(values[tonumber(i)])
    end)
    return (text:gsub(ESCAPED, "%%"))
end
function ns.Fmt(template, ...)
    local agree = Locale.grammar.Agree
    if agree then return agree(Fill(template, ...)) end
    return Fill(template, ...)
end

-- A key looked up and filled: ns.T("Met %s", name).
function ns.T(key, ...)
    if select("#", ...) == 0 then return L[key] end
    return ns.Fmt(L[key], ...)
end


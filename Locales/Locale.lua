-- A zone or dungeon after a preposition. The client gives a bare name
-- ("Brachland"), and the preposition and the name are one unit in most
-- languages: German "im Brachland" / "ins Brachland" / "aus dem
-- Brachland", French "en Durotar" / "dans les Tarides", Russian
-- "в Дуротаре" (the name itself declines). So the phrase is the locale's,
-- and a template takes it whole, its key marked "##zone":
--
--   Fmt(L["Found %1$s %2$s##zone"], item, ns.ZoneIn(mapID, name))
--   -- "Found Linen Cloth in The Barrens"
--
-- `role` is the preposition's job (default "in"; also "to", "from",
-- "into", "through", "near", "at", "around", "round"). A locale fills:
--   grammar.ZONES[mapID][role]          "im Brachland" (only the zones that
--   grammar.DUNGEONS[instanceID][role]   need it: articles, declension)
--   grammar.PLACE[role]                  the rest: "in %s"
-- Any of them may be a function of the bare name instead of a text, for a
-- preposition that contracts, elides or declines with what follows
-- (Spanish "del Cruce", French "près d'Orgrimmar").
--   grammar.SUBZONES[name][role]        a subzone, which has no id, by the
--                                        name the client gives ("Wegekreuz"
--                                        -> "am Wegekreuz")
-- English needs no table. A subzone goes through ns.ZoneIn too, with no
-- mapID: ns.ZoneIn(nil, subZone, "at") is "at The Crossroads".
Locale.grammar.PLACE = {
    ["in"] = "in %s", to = "to %s", from = "from %s", into = "into %s",
    through = "through %s", near = "near %s", at = "at %s", around = "around %s", round = "round %s",
}
Locale.grammar.ZONES, Locale.grammar.DUNGEONS, Locale.grammar.SUBZONES = {}, {}, {}

local ENGLISH_PLACE = Locale.grammar.PLACE

local function Phrase(own, id, name, role)
    role = role or "in"
    local words = id and own[id]
    local own = words and words[role]
    if type(own) == "function" then return (Spaces(own(name or ""))) end
    if own then return (Spaces(own)) end
    local template = Locale.grammar.PLACE[role] or ENGLISH_PLACE[role] or ENGLISH_PLACE["in"]
    if type(template) == "function" then return (Spaces(template(name or ""))) end
    return ns.Fmt(template, name or "")
end

-- `name` is what the caller shows (the client's map name, or the zone
-- kept on a row); `mapID` may be nil for rows that have none.
function ns.ZoneIn(mapID, name, role)
    name = name or (mapID and ns.MapName and ns.MapName(mapID))
    if not mapID then return Phrase(Locale.grammar.SUBZONES, name, name, role) end
    return Phrase(Locale.grammar.ZONES, mapID, name, role)
end

-- Several places after one preposition: "in Mulgore and Durotar". `join`
-- makes the list (Format.List). English says the preposition once; a
-- locale whose every name takes its own (French "à Hurlevent et à
-- Orgrimmar", a Russian case per name) sets grammar.EACH_PLACE.
function ns.ZonesIn(names, role, join)
    if not Locale.grammar.EACH_PLACE then return ns.ZoneIn(nil, join(names), role) end
    local phrases = {}
    for i, name in ipairs(names) do phrases[i] = ns.ZoneIn(nil, name, role) end
    return join(phrases)
end

function ns.DungeonIn(instanceID, name, role)
    return Phrase(Locale.grammar.DUNGEONS, instanceID, name, role)
end
